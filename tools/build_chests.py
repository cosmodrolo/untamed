#!/usr/bin/env python3
"""Build Data/Chests_Forever.lua: the world's random treasure chests and every spot they can appear.

usage: build_chests.py SRC_DIR OUT_PATH
Source: cmangos classic-db (cdb/full.sql: gameobject_template and gameobject spawns). Only the random
world chests and footlockers (Battered, Solid, Large ..., Buccaneer's Strongbox), not quest chests.
Spots are world positions on the two continents (server x = north, y = west, as the game's
C_Map.GetMapPosFromWorldPos takes them); the addon turns them into map spots in game. Spots of
the same kind closer than 8 yards are merged.
"""
import re, sys, os

SRC, OUT = sys.argv[1], sys.argv[2]
SQL = os.path.join(SRC, "cdb", "full.sql")
TREASURE = ["Battered Chest", "Solid Chest", "Tattered Chest", "Large Battered Chest", "Large Solid Chest",
            "Large Iron Bound Chest", "Large Mithril Bound Chest", "Mithril Bound Chest", "Buccaneer's Strongbox",
            "Battered Footlocker", "Waterlogged Footlocker", "Dented Footlocker", "Mossy Footlocker", "Scarlet Footlocker"]

def log(*a): print(*a, file=sys.stderr)

def sql_rows(line):
    i = line.index("VALUES") + 6; n = len(line)
    while i < n:
        while i < n and line[i] != "(": i += 1
        if i >= n: break
        i += 1; vals = []; cur = []; inq = False
        while True:
            c = line[i]
            if inq:
                if c == "\\": cur.append(line[i + 1]); i += 2; continue
                if c == "'": inq = False
                else: cur.append(c)
            else:
                if c == "'": inq = True
                elif c == ",": vals.append("".join(cur)); cur = []
                elif c == ")": vals.append("".join(cur)); i += 1; break
                else: cur.append(c)
            i += 1
        yield vals

T = {"gameobject_template": [], "gameobject": []}
for line in open(SQL, encoding="utf-8", errors="replace"):
    m = re.match(r"INSERT INTO `(\w+)`", line)
    if m and m.group(1) in T: T[m.group(1)].extend(sql_rows(line))

kind_of = {}
for v in T["gameobject_template"]:
    if v[3] in TREASURE: kind_of[int(v[0])] = v[3]
used = [n for n in TREASURE if n in kind_of.values()]
kidx = {n: i + 1 for i, n in enumerate(used)}

spots = {0: [], 1: []}
for v in T["gameobject"]:
    oid, cont = int(v[1]), int(v[2])
    if oid not in kind_of or cont not in spots: continue
    k, x, y = kidx[kind_of[oid]], float(v[4]), float(v[5])
    if any(p[0] == k and (p[1] - x) ** 2 + (p[2] - y) ** 2 < 64 for p in spots[cont][-60:]): continue
    spots[cont].append((k, x, y))

def lstr(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
with open(OUT, "w", encoding="utf-8") as f:
    f.write("-- Generated by tools/build_chests.py from cmangos classic-db. Do not edit by hand.\n")
    f.write("local _, ns = ...\n")
    f.write("ns.ChestKinds = {" + ",".join(lstr(n) for n in used) + "}\n")
    f.write("-- [object id] = kind\n")
    f.write("ns.ChestIds = {" + ",".join("[%d]=%d" % (i, kidx[n]) for i, n in sorted(kind_of.items())) + "}\n")
    f.write("-- [continent] = { kind, worldX, worldY, ... }  (continent 0 Eastern Kingdoms, 1 Kalimdor)\n")
    f.write("ns.ChestWorld = {\n")
    for cont in (0, 1):
        f.write("  [%d]={%s},\n" % (cont, ",".join("%d,%d,%d" % (k, round(x), round(y)) for k, x, y in spots[cont])))
    f.write("}\n")
log("chest kinds", len(used), "spots", {c: len(s) for c, s in spots.items()})
