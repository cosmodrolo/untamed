"""Localized beast and service NPC names from QuestieDB l10n (GPL-3.0), for the ids in a Data/*.lua file.

usage: build_names.py SRC_DIR FLAVOR DATA_LUA OUT_LUA
"""
import re, sys, os, glob
SRC, FLAVOR, DATA, OUT = sys.argv[1:5]
folder = os.path.join(SRC, "QuestieDB/l10n", "Classic" if FLAVOR == "era" else "Forever", "lookupNpcs")
d = open(DATA, encoding="utf-8").read()
ids = set(int(x) for x in re.findall(r"^  \[(\d+)\]=\{", d, re.M))
ids |= set(int(x) for x in re.findall(r",(\d+)\},$", d, re.M))
def lstr(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = ["-- Localized NPC names (QuestieDB l10n, GPL-3.0). Generated by tools/build_names.py.", "local _, ns = ...",
       "local loc = GetLocale and GetLocale() or \"enUS\"", "local N = {}"]
total = 0
for path in sorted(glob.glob(os.path.join(folder, "*.lua"))):
    loc = os.path.basename(path)[:-4]
    names = {}
    for m in re.finditer(r'^\[(\d+)\] = \{"((?:[^"\\]|\\.)*)"', open(path, encoding="utf-8").read(), re.M):
        i = int(m.group(1))
        if i in ids: names[i] = m.group(2).replace('\\"', '"')
    if not names: continue
    total += len(names)
    out.append('if loc == "%s" then N = {%s} end' % (loc, ",".join("[%d]=%s" % (i, lstr(n)) for i, n in sorted(names.items()))))
out.append("ns.LocalNames = N")
open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(FLAVOR, "ids", len(ids), "localized names", total, file=sys.stderr)
