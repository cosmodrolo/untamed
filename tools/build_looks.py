#!/usr/bin/env python3
"""Build Data/Looks_Forever.lua: which look (creature display) each tameable beast uses.
Source: cmangos classic-db creature_template.ModelId1 (GPL-3.0), for the beasts already in Data/Forever.lua.
Beasts new in Forever aren't in that database and get no entry.
Usage: python3 tools/build_looks.py /path/to/src   (the folder holding cdb/full.sql)"""
import os, re, sys, collections
SRC = sys.argv[1] if len(sys.argv) > 1 else "/home/claude/src"
HERE = os.path.dirname(os.path.abspath(__file__))
def sql_rows(line):
    i = line.index("VALUES") + 6; n = len(line)
    while i < n:
        while i < n and line[i] != "(": i += 1
        if i >= n: break
        i += 1; vals = []; cur = []; inq = False
        while True:
            c = line[i]
            if inq:
                if c == "\\": cur.append(line[i + 1]); i += 2; continue
                if c == "'": inq = False
                else: cur.append(c)
            else:
                if c == "'": inq = True
                elif c == ",": vals.append("".join(cur)); cur = []
                elif c == ")": vals.append("".join(cur)); i += 1; break
                else: cur.append(c)
            i += 1
        yield vals
model = {}
for line in open(os.path.join(SRC, "cdb", "full.sql"), encoding="utf-8", errors="replace"):
    if line.startswith("INSERT INTO `creature_template`"):
        for v in sql_rows(line): model[int(v[0])] = (int(v[5] or 0), v[1])
beasts = {}
for m in re.finditer(r'^  \[(\d+)\]=\{"((?:[^"\\]|\\.)*)",(\d+),(\d+),"([^"]*)"', open(os.path.join(HERE, "..", "Data", "Forever.lua"), encoding="utf-8").read(), re.M):
    beasts[int(m.group(1))] = (m.group(2), m.group(5))
out, miss, fam = [], 0, collections.defaultdict(set)
for nid in sorted(beasts):
    d = model.get(nid)
    # only when the database's beast is the same beast (same name): Forever reuses some numbers
    if d and d[0] > 0 and d[1].lower() == beasts[nid][0].replace('\\"', '"').replace("\\'", "'").lower():
        out.append("[%d]=%d" % (nid, d[0])); fam[beasts[nid][1]].add(d[0])
    else: miss += 1
# tools/looks_groups.txt: display=look (same model and textures, any size), from Blizzard's CreatureDisplayInfo
group = {}
for line in open(os.path.join(HERE, "looks_groups.txt"), encoding="utf-8"):
    if line.startswith("#"): continue
    for d, g in re.findall(r"(\d+)=(\d+)", line): group[int(d)] = int(g)
used = sorted(set(int(x.split("=")[1]) for x in out))
nog = [d for d in used if d not in group]
if nog: print("displays without a look group:", nog, file=sys.stderr)
with open(os.path.join(HERE, "..", "Data", "Looks_Forever.lua"), "w", encoding="utf-8") as f:
    f.write("-- Untamed: the look (creature display) each beast uses. Generated by tools/build_looks.py; do not edit by hand.\n")
    f.write("-- Source: cmangos classic-db creature_template (GPL-3.0). Beasts new in Forever have no entry.\n")
    f.write("local _, ns = ...\nns.BeastLook = {" + ",".join(out) + "}\n")
    f.write("-- [display] = look: displays with the same look share a model and textures and differ only in size.\n")
    f.write("-- Source: Blizzard client table CreatureDisplayInfo, WoW Forever 1.60.1 (wago.tools).\n")
    f.write("ns.LookGroup = {" + ",".join("[%d]=%d" % (d, group[d]) for d in used if d in group) + "}\n")
    looks = collections.defaultdict(set)
    for o in out:
        n, d = o.strip("[").split("]=")
        looks[beasts[int(n)][1]].add(group.get(int(d), -int(d)))
    for k in sorted(looks): print("  looks", k, len(looks[k]), file=sys.stderr)
print("beasts", len(beasts), "with a look", len(out), "without", miss, file=sys.stderr)
for k in sorted(fam): print(" ", k, len(fam[k]), file=sys.stderr)
