#!/usr/bin/env python3
"""Build Data/Looks_Forever.lua: which look (creature display) each tameable beast uses.
Source: cmangos classic-db creature_template.ModelId1 (GPL-3.0), for the beasts already in Data/Forever.lua.
Beasts new in Forever aren't in that database and get no entry.
Usage: python3 tools/build_looks.py /path/to/src   (the folder holding cdb/full.sql)"""
import os, re, sys, collections
SRC = sys.argv[1] if len(sys.argv) > 1 else "/home/claude/src"
HERE = os.path.dirname(os.path.abspath(__file__))
def sql_rows(line):
    i = line.index("VALUES") + 6; n = len(line)
    while i < n:
        while i < n and line[i] != "(": i += 1
        if i >= n: break
        i += 1; vals = []; cur = []; inq = False
        while True:
            c = line[i]
            if inq:
                if c == "\\": cur.append(line[i + 1]); i += 2; continue
                if c == "'": inq = False
                else: cur.append(c)
            else:
                if c == "'": inq = True
                elif c == ",": vals.append("".join(cur)); cur = []
                elif c == ")": vals.append("".join(cur)); i += 1; break
                else: cur.append(c)
            i += 1
        yield vals
model = {}
for line in open(os.path.join(SRC, "cdb", "full.sql"), encoding="utf-8", errors="replace"):
    if line.startswith("INSERT INTO `creature_template`"):
        for v in sql_rows(line): model[int(v[0])] = ([int(x or 0) for x in v[5:9] if int(x or 0) > 0], v[1])
beasts = {}
for m in re.finditer(r'^  \[(\d+)\]=\{"((?:[^"\\]|\\.)*)",(\d+),(\d+),"([^"]*)"', open(os.path.join(HERE, "..", "Data", "Forever.lua"), encoding="utf-8").read(), re.M):
    beasts[int(m.group(1))] = (m.group(2), m.group(5))
# tools/looks_groups.txt: display=look:size
group, scale = {}, {}
for line in open(os.path.join(HERE, "looks_groups.txt"), encoding="utf-8"):
    if line.startswith("#"): continue
    for d, g, s in re.findall(r"(\d+)=(\d+):(\d+)", line): group[int(d)] = int(g); scale[int(d)] = int(s)
first, also, miss, used, fam = [], [], 0, set(), collections.defaultdict(set)
for nid in sorted(beasts):
    d = model.get(nid)
    # only when the database's beast is the same beast (same name): Forever reuses some numbers
    if d and d[0] and d[1].lower() == beasts[nid][0].replace('\\"', '"').replace("\\'", "'").lower():
        ds = d[0]
        first.append("[%d]=%d" % (nid, ds[0])); used.update(ds)
        # a beast the game gives several skins (it picks one each time the beast appears)
        more = [x for x in ds[1:] if group.get(x) != group.get(ds[0])]
        if more: also.append("[%d]={%s}" % (nid, ",".join(map(str, more))))
        for x in ds: fam[beasts[nid][1]].add(group.get(x, -x))
    else: miss += 1
nog = sorted(d for d in used if d not in group)
if nog: print("displays without a look group:", nog, file=sys.stderr)
with open(os.path.join(HERE, "..", "Data", "Looks_Forever.lua"), "w", encoding="utf-8") as f:
    f.write("-- Untamed: the look (creature display) each beast uses. Generated by tools/build_looks.py; do not edit by hand.\n")
    f.write("-- Source: cmangos classic-db creature_template (GPL-3.0). Beasts new in Forever have no entry.\n")
    f.write("local _, ns = ...\nns.BeastLook = {" + ",".join(first) + "}\n")
    f.write("-- beasts the game gives more than one skin: the other displays\n")
    f.write("ns.BeastLookAlso = {" + ",".join(also) + "}\n")
    f.write("-- [display] = look: displays with the same look share a model and textures and differ only in size.\n")
    f.write("-- [display] = size in percent, where it isn't 100.\n")
    f.write("-- Source: Blizzard client tables CreatureDisplayInfo and CreatureModelData, WoW Forever 1.60.1 (wago.tools).\n")
    f.write("ns.LookGroup = {" + ",".join("[%d]=%d" % (d, group[d]) for d in sorted(used) if d in group) + "}\n")
    f.write("ns.LookSize = {" + ",".join("[%d]=%d" % (d, scale[d]) for d in sorted(used) if scale.get(d, 100) != 100) + "}\n")
print("beasts", len(beasts), "with a look", len(first), "without", miss, "with several skins", len(also), file=sys.stderr)
for k in sorted(fam): print("  looks", k, len(fam[k]), file=sys.stderr)
