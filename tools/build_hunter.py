#!/usr/bin/env python3
"""Build Data/Hunter_<Flavor>.lua: trainer spells, a gear score table, and hunter class quests.

usage: build_hunter.py CMANGOS_SQL QUESTIEDB_DIR FLAVOR OUT_PATH

Sources (GPL-3.0, like Untamed):
  cmangos classic-db  npc_trainer(_template), spell_template, item_template
  QuestieDB           quest data (hunter-only quests), item sources
Trainer spells and gear are Classic Era data; on Forever only the quests are built.
"""
import os, re, sys
from lupa import LuaRuntime

SQL, Q, FLAVOR, OUT = sys.argv[1:5]

def log(*a): print(*a, file=sys.stderr)

def rows(line):
    i = line.index("VALUES") + 6; n = len(line)
    while i < n:
        while i < n and line[i] != "(": i += 1
        if i >= n: break
        i += 1; vals = []; cur = []; inq = False
        while True:
            c = line[i]
            if inq:
                if c == "\\": cur.append(line[i + 1]); i += 2; continue
                if c == "'": inq = False
                else: cur.append(c)
            else:
                if c == "'": inq = True
                elif c == ",": vals.append("".join(cur)); cur = []
                elif c == ")": vals.append("".join(cur)); i += 1; break
                else: cur.append(c)
            i += 1
        yield vals

want = {"npc_trainer", "npc_trainer_template", "creature_template", "spell_template", "item_template"}
T = {k: [] for k in want}
for line in open(SQL, encoding="utf-8", errors="replace"):
    m = re.match(r"INSERT INTO `(\w+)`", line)
    if m and m.group(1) in want: T[m.group(1)].extend(rows(line))
SP = {int(v[0]): v for v in T["spell_template"]}

def s(v): return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'
out = ["-- Generated by tools/build_hunter.py from cmangos classic-db and QuestieDB (GPL-3.0). Do not edit.",
       "local _, ns = ..."]

# ------------------------------------------------------------------ trainer spells
if FLAVOR == "era":
    ents, tmpl = set(), set()
    for v in T["creature_template"]:
        if v[71] == "0" and v[73] == "3":
            ents.add(int(v[0]))
            if v[75] not in ("", "0"): tmpl.add(int(v[75]))
    teach = {}
    for v in T["npc_trainer_template"]:
        if int(v[0]) in tmpl: teach[int(v[1])] = (int(v[2]), int(v[5]))
    for v in T["npc_trainer"]:
        if int(v[0]) in ents: teach[int(v[1])] = (int(v[2]), int(v[5]))
    spells = []
    for sid, (cost, lvl) in teach.items():
        sp = SP.get(sid)
        if not sp: continue
        real = int(sp[109]) if sp[61] == "36" and sp[109] not in ("", "0") else sid
        rsp = SP.get(real, sp)
        name, rank = rsp[119], rsp[127]
        rk = re.search(r"(\d+)", rank or "")
        spells.append((lvl, real, cost, name, int(rk.group(1)) if rk else 0))
    spells.sort(key=lambda x: (x[0], x[3], x[4]))
    out.append("-- {level, spellID, copper, English name, rank}")
    out.append("ns.TrainerSpells = {")
    for l, sid, c, n, r in spells: out.append("{%d,%d,%d,%s,%d}," % (l, sid, c, s(n), r))
    out.append("}")
    log("trainer spells", len(spells))

# ------------------------------------------------------------------ gear scores
if FLAVOR == "era":
    AURA_W = {52: ("crit", 20), 54: ("hit", 18), 99: ("ap", 1), 124: ("rap", 1)}
    def equip_bonus(sid):
        sp = SP.get(sid)
        if not sp: return 0
        tot = 0
        for k in range(3):
            aura = int(sp[91 + k] or 0)
            if aura in AURA_W:
                val = int(sp[76 + k] or 0) + int(sp[64 + k] or 0)
                tot += val * AURA_W[aura][1]
        return tot
    STAT_W = {3: 2.4, 7: 0.5, 5: 0.3, 4: 0.1, 1: 0.05}
    SLOT = {1: "HEAD", 2: "NECK", 3: "SHOULDER", 5: "CHEST", 20: "CHEST", 6: "WAIST", 7: "LEGS", 8: "FEET", 9: "WRIST",
            10: "HANDS", 11: "FINGER", 12: "TRINKET", 16: "BACK", 13: "WEAPON", 17: "WEAPON", 21: "WEAPON", 22: "OFFHAND",
            15: "RANGED", 26: "RANGED"}
    MELEE_OK = {0, 1, 6, 7, 8, 10, 13, 15}
    RANGED_OK = {2, 3, 18}
    gear = []
    for v in T["item_template"]:
        cls, sub, inv = int(v[1]), int(v[2]), int(v[10])
        slot = SLOT.get(inv)
        if not slot: continue
        ac = int(v[11])
        if ac not in (-1, 0) and not (ac & 4) and ac != 32767: continue
        if int(v[18] or 0) > 0: continue                       # PvP rank items
        if cls == 4 and sub not in (0, 1, 2, 3): continue      # misc, cloth, leather, mail
        if cls == 2:
            if inv in (15, 26):
                if sub not in RANGED_OK: continue
            elif sub not in MELEE_OK: continue
        if cls not in (2, 4): continue
        if int(v[5]) < 1: continue                             # skip grey items
        score = 0.0
        for k in range(10):
            t, val = int(v[25 + 2 * k] or 0), int(v[26 + 2 * k] or 0)
            score += STAT_W.get(t, 0) * val
        for k in range(5):
            sid, trig = int(v[70 + 7 * k] or 0), int(v[71 + 7 * k] or 0)
            if sid and trig == 1: score += equip_bonus(sid)
        if slot == "RANGED":
            delay = int(v[67] or 0)
            if delay > 0:
                dps = (float(v[45]) + float(v[46])) / 2 / (delay / 1000.0)
                score += dps * 14
        score = round(score)
        if score <= 0: continue
        mail = 1 if (cls == 4 and sub == 3) else 0
        req = int(v[14])
        if req == 0: req = max(1, min(60, int(v[13]) - 5))   # some items have no required level in the data
        gear.append((int(v[0]), slot, req, score, mail))
    out.append("-- [itemID] = {slot, requiredLevel, score, isMail}. Score: agility x2.4, attack power x1, crit% x20, hit% x18,")
    out.append("-- stamina x0.5, intellect x0.3, ranged weapon DPS x14.")
    out.append("ns.GearItems = {")
    for iid, slot, lvl, sc, mail in sorted(gear):
        out.append("[%d]={%s,%d,%d,%d}," % (iid, s(slot), lvl, sc, mail))
    out.append("}")
    log("gear items", len(gear))

# ------------------------------------------------------------------ hunter quests
lua = LuaRuntime(unpack_returned_tuples=True)
pre = "Classic/classic" if FLAVOR == "era" else "Forever/forever"
text = open(os.path.join(Q, "data", pre + "QuestDB.lua"), encoding="utf-8").read()
QD = lua.execute(text[text.index("[[return {") + 2: text.rindex("}]]") + 1])
def pl(t):
    if t is None: return []
    return [t[k] for k in sorted(t.keys())]
quests = []
for qid in QD.keys():
    r = QD[qid]
    rc = r[7] or 0
    if rc != 4: continue
    name = r[1]
    if not name or "test" in name.lower() or name.startswith("["): continue
    sb = r[2]
    npcS = pl(sb[1]) if sb is not None and sb[1] is not None else []
    objS = pl(sb[2]) if sb is not None and sb[2] is not None else []
    itemS = pl(sb[3]) if sb is not None and sb[3] is not None else []
    fb = r[3]
    npcE = pl(fb[1]) if fb is not None and fb[1] is not None else []
    preS = pl(r[13]); preG = pl(r[12])
    quests.append((int(qid), name, r[5] or 0, r[4] or 0, r[6] or 0, npcS[0] if npcS else 0, objS[0] if objS else 0,
                   itemS[0] if itemS else 0, npcE[0] if npcE else 0, (preS or preG or [0])[0], r[22] or 0))
quests.sort(key=lambda q: (q[3], q[2], q[0]))
out.append("-- {questID, name, questLevel, requiredLevel, raceMask, startNpc, startObject, startItem, endNpc, preQuest, nextQuest}")
out.append("ns.HunterQuests = {")
for q in quests:
    out.append("{%d,%s,%d,%d,%d,%d,%d,%d,%d,%d,%d}," % (q[0], s(q[1]), q[2], q[3], q[4], q[5], q[6], q[7], q[8], q[9], q[10]))
out.append("}")
log("hunter quests", len(quests))

open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
log("wrote", OUT, os.path.getsize(OUT))
